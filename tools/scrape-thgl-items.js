#!/usr/bin/env node
'use strict';
// Import numeric IDs + item names from the public Aniimo.th.gl index.
// Never infer HC sell prices from this catalog.
const fs=require('node:fs');
const path=require('node:path');
const root='https://aniimo.th.gl/db/items';
const out=path.resolve(__dirname,'../data/thgl-items.js');
const decode=s=>String(s).replace(/&amp;/g,'&').replace(/&quot;/g,'"').replace(/&#39;|&apos;/g,"'").replace(/&lt;/g,'<').replace(/&gt;/g,'>').replace(/&#(\d+);/g,(_,n)=>String.fromCodePoint(+n)).replace(/&#x([\da-f]+);/gi,(_,n)=>String.fromCodePoint(parseInt(n,16)));
const clean=s=>decode(s.replace(/<[^>]+>/g,' ').replace(/\s+/g,' ').trim());
async function main(){
 const response=await fetch(root,{headers:{'user-agent':'AniimoHomelandPlannerCatalog/1.0','accept':'text/html'}});
 if(!response.ok)throw new Error('Item index fetch returned HTTP '+response.status);
 const html=await response.text();
 const expected=Number(html.match(/([\d,]+)\s+entries/i)?.[1]?.replace(/,/g,'')||0);
 const map=new Map();
 // Standard HTML anchors: the item ID is the stable identity; link text is only the display name.
 const re=/<a\b([^>]*\bhref\s*=\s*["'][^"']*\/db\/items\/item_(\d+)[^"']*["'][^>]*)>([\s\S]*?)<\/a>/gi;
 let m;
 while((m=re.exec(html))){
   const id=m[2],name=clean(m[3]);
   if(name&&!/^Item\s+\d+$/i.test(name)&&!map.has(id))map.set(id,{id,name,url:root+'/item_'+id});
 }
 // Next/SSR apps can wrap item labels in children and have anchors with reverse attribute ordering;
 // discover IDs, but refuse to publish without a matching verified display name.
 const observed=[...html.matchAll(/\/db\/items\/item_(\d+)/g)].map(x=>x[1]);
 const uniqueObserved=new Set(observed).size;
 const coverage=expected?map.size/expected:0;
 if(expected<3000||map.size<3000||coverage<0.90)
   throw new Error('Refusing incomplete item catalog: '+JSON.stringify({expected,parsed:map.size,observed:uniqueObserved,coverage}));
 const byId=Object.fromEntries([...map.entries()].sort((a,b)=>Number(a[0])-Number(b[0])));
 const payload={format:'aniimo-thgl-items-v1',source:root,scrapedAt:new Date().toISOString(),counts:{items:map.size,advertised:expected},byId};
 fs.writeFileSync(out,'// Generated by tools/scrape-thgl-items.js; names and IDs only (no assumed sale prices).\nwindow.ANIIMO_THGL_ITEMS='+JSON.stringify(payload)+';\n');
 console.log('Saved',out,'items:',map.size,'advertised:',expected);
}
main().catch(e=>{console.error(e);process.exitCode=1;});
